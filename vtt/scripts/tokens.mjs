// Turns the color tokens exported from Figma (assets/dnd-tokens-dark.json) into CSS variables:
// "txt/primary" -> --txt-primary. Deprecated tokens are skipped. Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const here = (p) => fileURLToPath(new URL(p, import.meta.url))
const source = JSON.parse(readFileSync(here('../../assets/dnd-tokens-dark.json'), 'utf8'))

const lines = []
const walk = (node, path) => {
  if (node && node.$type === 'color') {
    const name = path.join('/')
    if (name.includes('[deprecated]')) return
    const { hex, alpha, components } = node.$value
    const value = alpha === 1
      ? hex.toLowerCase()
      : `rgba(${components.map((c) => Math.round(c * 255)).join(', ')}, ${Math.round(alpha * 100) / 100})`
    lines.push(`  --${path.join('-')}: ${value}; /* ${name} */`)
    return
  }
  for (const [key, child] of Object.entries(node)) {
    if (!key.startsWith('$') && child && typeof child === 'object') walk(child, [...path, key])
  }
}
walk(source, [])

writeFileSync(here('../src/ui/tokens/colors.css'),
  `/* Generated by scripts/tokens.mjs from assets/dnd-tokens-dark.json — do not edit by hand. */\n:root {\n${lines.join('\n')}\n}\n`)
console.log(`tokens: ${lines.length} colors -> src/ui/tokens/colors.css`)
